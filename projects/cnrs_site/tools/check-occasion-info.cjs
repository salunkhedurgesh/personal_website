// Run with: node tools/check-occasion-info.cjs
const assert = require('node:assert/strict');
const {readFileSync} = require('node:fs');
const {runInNewContext} = require('node:vm');
const {join} = require('node:path');
const context = {window: {THREE: {}}, matchMedia: () => ({matches: false})};
runInNewContext(readFileSync(join(__dirname, '../js/scene.js'), 'utf8'), context);
const info = context.window.Studio3D.occasionInfo;
assert.equal(context.window.Studio3D.classify('2027-01-26'), 'india');
assert.equal(info('india', '2027-01-26').title, 'Indian Republic Day');
assert.equal(info('india', '2027-01-26').dates, '26 Jan');
assert.equal(context.window.Studio3D.classify('2027-08-15'), 'india');
assert.equal(info('india', '2027-08-15').title, 'Indian Independence Day');
assert.equal(info('india', '2027-08-15').dates, '15 Aug');
assert.equal(info('india', '2027-11-05').dates, '26 Jan · 15 Aug');
assert.equal(context.window.Studio3D.classify('2027-07-14'), 'france');
assert.equal(info('france', '2027-07-14').title, 'France · la Fête nationale');
assert.equal(info('france', '2027-07-14').dates, '14 Jul');
assert.equal(info('diwali', '2027-10-29').dates, '26 Oct – 1 Nov');
assert.equal(info('diwali', '2026-11-05').dates, '5 Nov – 11 Nov');
assert.equal(info('holi', '2029-03-01').dates, '26 Feb – 4 Mar');
assert.equal(info('christmas', '2026-12-01').dates, '22 Dec – 28 Dec');
assert.equal(info('halloween', '2026-10-25').dates, '25 Oct – 31 Oct');
assert.equal(info('snow', '2028-02-01').dates, '');
assert.equal(info('snow', '2026-12-01').dates, '');
assert.equal(info('snow', '2026-11-05', {weather_code: 75}).dates, '');
assert.equal(info('snow', '2026-11-05', {temperature_2m: -2.4}).temperature, -2.4);
assert.equal(info('snow', '2026-11-05', null).temperature, null);
assert.equal(info('snow', '2026-11-05').title, 'Strasbourg Winter');
assert.equal(info('diwali', '2035-11-01').dates, '');
console.log('Occasion dates, date-free winter title, and temperature handling passed.');
